"""Generate the native add-in's Revit capture core from the local Agentulator adapter.

The output has no Agentulator references. Both plugin variants therefore use the
same callback and V2DG writer implementation without referencing another repo.
"""
from pathlib import Path


root = Path(__file__).resolve().parents[1]
source = (root / "plugin" / "View2dExport" / "View2dExport.cs").read_text(encoding="utf-8-sig")
marker = "    private static bool IsDrawable2d(ViewType t)"
if source.count(marker) != 1 or not source.rstrip().endswith("}"):
    raise SystemExit("Could not locate the capture core in View2dExport.cs")
core = source[source.index(marker):].rstrip() + "\n"
if "Agentulator." in core or "ToolContext" in core:
    raise SystemExit("The capture core unexpectedly depends on Agentulator")

prefix = '''// Generated by scripts/generate_native_core.py from plugin/View2dExport/View2dExport.cs.
// Edit the capture callbacks and V2DG writer in the Agentulator adapter, then regenerate.
#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Autodesk.Revit.DB;

namespace Hack2DExport;

internal sealed record V2dgExportResult(byte[] Bytes, object[] LinePatterns, int ElementRows,
    int Primitives, long[] MissingSelectedElementIds);

internal static class View2dCore
{
    public static bool Supports(View view) => !view.IsTemplate && IsDrawable2d(view.ViewType);

    public static V2dgExportResult Export(Document document, View view, HashSet<long>? selectedIds)
    {
        if (!Supports(view)) throw new ArgumentException("Select a drawable native 2D view.", nameof(view));
        var capture = new Capture(document, view, () => false, 0, selectedIds);
        using var exporter = new CustomExporter(document, capture)
        {
            IncludeGeometricObjects = true,
            Export2DIncludingAnnotationObjects = true,
            Export2DGeometricObjectsIncludingPatternLines = true,
            ShouldStopOnError = false,
            Export2DForceDisplayStyle = DisplayStyle.Undefined
        };
        exporter.Export(view);
        if (capture.WasCanceled) throw new InvalidOperationException("The 2D export was cancelled.");
        return new V2dgExportResult(Encode(capture), UsedLinePatterns(document, capture),
            capture.Rows.Count, capture.PrimitiveCount,
            selectedIds?.Except(capture.Rows.Select(row => row.ElementId)).ToArray() ?? Array.Empty<long>());
    }

'''
output = root / "addin" / "View2dCore.g.cs"
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text(prefix + core, encoding="utf-8")
print(f"Generated {output} ({len(prefix + core)} chars)")
